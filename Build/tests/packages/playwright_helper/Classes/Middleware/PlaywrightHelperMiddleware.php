namespace TYPO3Tests\PlaywrightHelper\Middleware;

use Doctrine\DBAL\Schema\Table;
use Doctrine\DBAL\Types\Types;
use Psr\Http\Message\ResponseInterface;
use Psr\Http\Message\ServerRequestInterface;
use Psr\Http\Server\MiddlewareInterface;
use Psr\Http\Server\RequestHandlerInterface;
use TYPO3\CMS\Core\Core\Environment;
use TYPO3\CMS\Core\Database\Connection;
use TYPO3\CMS\Core\Database\ConnectionPool;
use TYPO3\CMS\Core\Http\JsonResponse;
use TYPO3\CMS\Install\Service\EnableFileService;

/**
 * Middleware to handle Playwright helper requests early in the backend stack.
 * Endpoints live under /typo3/playwright-helper/ and run before
 * typo3/cms-backend/locked-backend, so they work without an authenticated
 * backend session.
 *
 * Requests are authenticated against a per-instance secret generated by
 * Build/Scripts/setupAcceptanceComposer.sh and stored at
 * var/transient/playwright-helper.secret. Callers must send the secret in
 * the X-Playwright-Helper-Secret request header. Requests without a matching
 * secret are rejected with 403. The Playwright fixture reads the same file
 * and includes the header for every helper request.
 *
 * The package shipping this middleware (typo3tests/playwright-helper) lives
 * under Build/tests/packages/ and is composer-required only by
 * Build/Scripts/setupAcceptanceComposer.sh. It must not be added as a
 * dependency anywhere else, and it must not be loaded as an extension in any
 * non-test TYPO3 installation.
 *
 * @internal Testing only.
 */
final readonly class PlaywrightHelperMiddleware implements MiddlewareInterface
{
    private const string PATH_PREFIX = '/typo3/playwright-helper/';
    private const string SECRET_HEADER = 'X-Playwright-Helper-Secret';
    private const string SECRET_FILE = '/transient/playwright-helper.secret';
    private const string UNUSED_TABLE = 'tx_playwrighthelper_unused_table';
    private const string DELETED_PREFIX = 'zzz_deleted_';

    public function __construct(
        private ConnectionPool $connectionPool,
    ) {}

    public function process(ServerRequestInterface $request, RequestHandlerInterface $handler): ResponseInterface
    {
        $path = $request->getUri()->getPath();
        if (!str_starts_with($path, self::PATH_PREFIX)) {
            return $handler->handle($request);
        }
        if (!$this->isAuthenticated($request)) {
            return new JsonResponse(['error' => 'forbidden'], 403);
        }
        switch (substr($path, strlen(self::PATH_PREFIX))) {
            case 'install-tool/enable':
                EnableFileService::createInstallToolEnableFile();
                return $this->createInstallToolStatusResponse();
            case 'install-tool/disable':
                EnableFileService::removeInstallToolEnableFile();
                return $this->createInstallToolStatusResponse();
            case 'install-tool/status':
                return $this->createInstallToolStatusResponse();
            case 'database/unused-table/create':
                return $this->createUnusedTable();
            case 'database/unused-table/drop':
                return $this->dropUnusedTable();
            default:
                return new JsonResponse(['error' => 'not found'], 404);
        }
    }

    private function createInstallToolStatusResponse(): ResponseInterface
    {
        return new JsonResponse([
            'enabled' => EnableFileService::installToolEnableFileExists(),
        ]);
    }

    /**
     * Creates a table with one row that no ext_tables.sql defines, so the
     * database analyzer offers to rename it with the deletion prefix and to
     * drop it afterwards.
     */
    private function createUnusedTable(): ResponseInterface
    {
        $connection = $this->getDefaultConnection();
        $this->dropUnusedTables($connection);
        $table = new Table(self::UNUSED_TABLE);
        $table->addColumn('uid', Types::INTEGER);
        $connection->createSchemaManager()->createTable($table);
        $connection->insert(self::UNUSED_TABLE, ['uid' => 1]);
        return new JsonResponse([
            'table' => self::UNUSED_TABLE,
            'deletedTable' => self::DELETED_PREFIX . self::UNUSED_TABLE,
            'rows' => 1,
        ]);
    }

    /**
     * Drops the unused table, no matter whether the analyzer has already
     * renamed it with the deletion prefix.
     */
    private function dropUnusedTable(): ResponseInterface
    {
        $this->dropUnusedTables($this->getDefaultConnection());
        return new JsonResponse([
            'table' => self::UNUSED_TABLE,
            'deletedTable' => self::DELETED_PREFIX . self::UNUSED_TABLE,
        ]);
    }

    private function dropUnusedTables(Connection $connection): void
    {
        $schemaManager = $connection->createSchemaManager();
        foreach ([self::UNUSED_TABLE, self::DELETED_PREFIX . self::UNUSED_TABLE] as $tableName) {
            if ($schemaManager->tablesExist([$tableName])) {
                $schemaManager->dropTable($tableName);
            }
        }
    }

    private function getDefaultConnection(): Connection
    {
        return $this->connectionPool->getConnectionByName(ConnectionPool::DEFAULT_CONNECTION_NAME);
    }

    private function isAuthenticated(ServerRequestInterface $request): bool
    {
        $secretFile = Environment::getVarPath() . self::SECRET_FILE;
        if (!is_file($secretFile)) {
            return false;
        }
        $expected = trim((string)file_get_contents($secretFile));
        if ($expected === '') {
            return false;
        }
        $provided = $request->getHeaderLine(self::SECRET_HEADER);
        return $provided !== '' && hash_equals($expected, $provided);
    }
}
